"""Writes goldens.h for torch_generator_test.cpp from torch.randn.

Run from the repository root with torch installed, then format with lintrunner:

    python extension/random/test/generate_goldens.py
"""

from pathlib import Path

import torch

# Seeds and successive draws from one generator. Counts that are not a
# multiple of 16 cover the redrawn last block; seeds above 2**32 cover the
# truncation to the 32-bit engine seed.
CASES = [
    (0, [("float32", 37)]),
    (42, [("float32", 100)]),
    (42, [("float16", 37)]),
    (7, [("bfloat16", 100)]),
    (2**32 + 5, [("float32", 16)]),
    (3, [("float32", 37), ("float16", 50), ("float32", 32)]),
]


def bits(tensor):
    if tensor.dtype == torch.float32:
        return [value & 0xFFFFFFFF for value in tensor.view(torch.int32).tolist()]
    return [value & 0xFFFF for value in tensor.view(torch.int16).tolist()]


def main():
    cases = []
    for seed, draws in CASES:
        generator = torch.Generator().manual_seed(seed)
        rendered = []
        for dtype, numel in draws:
            values = torch.randn(
                numel, generator=generator, dtype=getattr(torch, dtype)
            )
            rendered.append(
                f'{{"{dtype}", {{{", ".join(str(b) for b in bits(values))}}}}}'
            )
        cases.append(f"{{{seed}u, {{{', '.join(rendered)}}}}}")
    path = Path(__file__).with_name("goldens.h")
    path.write_text(
        f"""/*
 * Copyright (c) Meta Platforms, Inc. and affiliates.
 * All rights reserved.
 *
 * This source code is licensed under the BSD-style license found in the
 * LICENSE file in the root directory of this source tree.
 */

// Generated by generate_goldens.py from torch {torch.__version__}.

#pragma once

#include <cstdint>
#include <vector>

struct GoldenDraw {{
  const char* dtype;
  std::vector<uint32_t> bits;
}};

struct GoldenCase {{
  uint64_t seed;
  std::vector<GoldenDraw> draws;
}};

inline const std::vector<GoldenCase> kGoldenCases = {{{", ".join(cases)}}};
"""
    )
    print(f"Wrote {path}")


if __name__ == "__main__":
    main()
