// Pins the image path's resize to Pillow's LANCZOS.
//
// The reference preprocessing resizes with PIL LANCZOS on the sRGB bytes. The
// runner used to resize with stb Catmull-Rom in linear light instead, which
// differs on essentially every image.
//
// Goldens are Pillow's own output, emitted by tests/gen_resize_golden.py. The
// Python side of the same table lives in
// tests/test_vision_precompute.py::ResizeReferenceParityTest, so a Pillow
// upgrade that changes resampling fails there rather than silently drifting
// away from the C++.

#include <executorch/examples/models/muse-glimmer/vision/preprocess.h>

