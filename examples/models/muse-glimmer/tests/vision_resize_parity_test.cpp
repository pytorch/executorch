// Deterministic RGB content with a hard edge and two gradients. Must stay
// byte-identical to make_image() in tests/gen_resize_golden.py.
std::vector<uint8_t> MakeImage(int32_t w, int32_t h) {
  std::vector<uint8_t> px;
  px.reserve(static_cast<size_t>(w) * h * 3);
  for (int32_t y = 0; y < h; ++y) {
    for (int32_t x = 0; x < w; ++x) {
      px.push_back(static_cast<uint8_t>((x * 37 + y * 11) % 256));
      px.push_back((x < w / 3 && y < h / 2) ? 255 : 16);
      px.push_back(static_cast<uint8_t>((x * x + y * y * 3) % 256));
    }
  }
  return px;
}

