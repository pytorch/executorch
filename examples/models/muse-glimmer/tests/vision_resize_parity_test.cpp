TEST(VisionResizeParityTest, MatchesPillowLanczos) {
  for (const ResizeCase& resize_case : ReferenceResizes()) {
    const std::vector<uint8_t> src =
        MakeImage(resize_case.src_w, resize_case.src_h);

    const std::vector<uint8_t> actual = resize_rgb_lanczos(
        src.data(),
        resize_case.src_w,
        resize_case.src_h,
        resize_case.dst_w,
        resize_case.dst_h);

    EXPECT_EQ(actual, resize_case.expected)
        << resize_case.src_w << "x" << resize_case.src_h << " -> "
        << resize_case.dst_w << "x" << resize_case.dst_h;
  }
}

