import torch

from executorch.examples.models.mobilenet_v3 import MV3Model
from executorch.examples.nxp.models.mobilenet_v2 import MobileNetV2


class MobileNetV3(MobileNetV2):
    """
    MobileNet V3 model. Shares most parameters with MobileNet V2.

    Calibration data for MobileNet V2 and V3 can be generated by backends/nxp/tests/prepare_calibration_data_mobilenet_v2.py
    from Imagenette dataset, a subset of 10 classes from ImageNet dataset the model is trained on.
    """

    def _init_eager_model(self) -> torch.nn.Module:
        return MV3Model().get_eager_model().eval()
