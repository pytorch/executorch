import { concat, encodeWav, formatClock } from '../audio/pcm.js';
import { createWaveform } from '../audio/waveform.js';
import { isPreview } from '../config/catalog.js';
import { getModel } from '../config/models.js';
import { gpuState } from '../gpu/context.js';
import { h, replace } from '../lib/dom.js';
import { formatBytes, formatInt, formatMs } from '../lib/format.js';
import { hashString } from '../lib/prng.js';
import { isPhononLoaded, loadPhonon, PHONON_MODEL_ID } from '../runtime/phonon.js';
import { resolveModelSource } from '../runtime/sources.js';
import { appIcon } from './app-icons.js';
import { attributionEl, creditEl, licenseBadgeEl } from './badges.js';
import { browseMore, detailHeader } from './detail-shell.js';
import { gpuFallbackPanel } from './gpu-fallback.js';
import { hfBadge } from './hf-badge.js';
import { icon } from './icons.js';
import { confirmModelMemory } from './memory-guard.js';
import { metricTile } from './metric.js';
import { onDeviceNote } from './on-device.js';

const SAMPLES = [
  'The quick brown fox jumps over the lazy dog.',
  'This voice is generated by a small model running entirely on your device.',
  'Please call me back when you have a moment, and we can talk about the plan.',
];
const MAX_CHARS = 1200;
const VOICE_KEY = 'etwg-tts-voice';
const LOAD_STAGES = [
  { id: 'runtime', label: 'Start the ExecuTorch runtime', weight: 0.04 },
  { id: 'download', label: 'Download the model', weight: 0.84 },
  { id: 'gpu', label: 'Upload graphs to the GPU', weight: 0.12 },
];
// Playback starts a little after the first frame so the next one is ready in time.
const LEAD_SEC = 0.06;

const savedVoice = () => {
  try {
    return localStorage.getItem(VOICE_KEY);
  } catch {
    return null;
  }
};

export function mountTts(root, demo) {
  const model = getModel(PHONON_MODEL_ID);
  const state = {
    phase: isPhononLoaded() ? 'ready' : 'checking', // checking | unavailable | idle | loading | ready | error
    reasons: [],
    source: null,
    load: { stage: null, fractions: {}, loaded: 0, total: 0, detail: '' },
    loadError: null,
    loadMs: null,
    gpu: gpuState.get(),
    voice: savedVoice(),
    speak: 'idle', // idle | speaking | done | error
    error: null,
    run: null, // { pcm: Float32Array[], stats, chunk, chunks, frames, firstAudioMs, rtf }
  };
  let tts = null;
  let disposed = false;
  let loadAbort = null;
  let speakAbort = null;
  let audio = null;
  let nextAt = 0;
  let raf = 0;

  // ---------- persistent elements ----------
  const voiceSelect = h('select', { class: 'select tts-voice', 'aria-label': 'Voice', onchange: (e) => setVoice(e.target.value) });
  const stage = h('section', { class: 'tts-stage', 'aria-label': 'Text to speech' });
  const metricsPanel = h('aside', { class: 'metrics', 'aria-label': 'About this run' });
  const input = h('textarea', {
    class: 'tts-input',
    rows: 4,
    maxlength: MAX_CHARS,
    placeholder: 'Type something to say…',
    'aria-label': 'Text to speak',
    oninput: () => updateControls(),
  });
  input.value = SAMPLES[0];
  const countEl = h('span', { class: 'tts-count' });
  const speakBtn = h('button', { class: 'btn btn--primary tts-speak', type: 'button', onclick: () => (state.speak === 'speaking' ? stop() : speak()) });
  const downloadBtn = h('button', { class: 'btn btn--ghost btn--sm', type: 'button', onclick: () => download() }, icon('download', 15), 'Download WAV');
  const replayBtn = h('button', { class: 'btn btn--ghost btn--sm', type: 'button', onclick: () => replay() }, icon('play', 15), 'Play again');
  const statusEl = h('p', { class: 'tts-status', 'aria-live': 'polite' });
  const waveCanvas = h('canvas', { class: 'tts-wave', 'aria-hidden': 'true' });
  const wave = createWaveform(waveCanvas);
  const clock = h('span', { class: 'tts-clock' }, '00:00');

  replace(
    root,
    h(
      'div',
      { class: 'page detail tts-page' },
      detailHeader(demo, { controls: h('label', { class: 'field' }, h('span', { class: 'field__label' }, 'Voice'), voiceSelect) }),
      h(
        'div',
        { class: 'truth' },
        h(
          'div',
          { class: 'truth__item truth__item--ok' },
          h('span', { class: 'truth__tag' }, 'Runs on your GPU'),
          h('span', null, 'Phonon generates the speech frame by frame through ExecuTorch on WebGPU, audio decoder included. Your text never leaves this tab.'),
        ),
        isPreview(demo)
          ? h('div', { class: 'truth__item' }, h('span', { class: 'truth__tag' }, 'Preview'), h('span', null, 'Not published yet: the model files come from this machine.'))
          : null,
      ),
      h('div', { class: 'tts-layout' }, stage, metricsPanel),
      browseMore(demo.id),
    ),
  );

  const unsubscribeGpu = gpuState.subscribe((s) => {
    const changed = s.status !== state.gpu.status;
    state.gpu = s;
    if (changed && state.phase !== 'ready') renderStage();
  });

  // ---------- model ----------
  (async () => {
    const source = await resolveModelSource(model);
    if (disposed) return;
    state.source = source;
    if (state.phase === 'ready') {
      tts = await loadPhonon();
      return renderAll();
    }
    if (source.kind === 'unavailable') Object.assign(state, { phase: 'unavailable', reasons: source.reasons });
    else state.phase = 'idle';
    renderAll();
  })();
  renderAll();

  async function load() {
    if (state.phase === 'loading') return;
    if (!(await confirmModelMemory(model))) return;
    loadAbort = new AbortController();
    const t0 = performance.now();
    Object.assign(state, { phase: 'loading', loadError: null, load: { stage: 'runtime', fractions: {}, loaded: 0, total: 0, detail: '' } });
    renderStage();
    try {
      tts = await loadPhonon({
        signal: loadAbort.signal,
        onProgress: (p) => {
          state.load.stage = p.stage;
          state.load.fractions[p.stage] = p.fraction;
          if (p.stage === 'download') Object.assign(state.load, { loaded: p.loaded, total: p.total });
          state.load.detail = p.detail ?? '';
          updateLoader();
        },
      });
      if (disposed) return;
      state.loadMs = performance.now() - t0;
      state.phase = 'ready';
      renderAll();
    } catch (err) {
      if (disposed || err.name === 'AbortError') return;
      Object.assign(state, { phase: 'error', loadError: err.message });
      renderStage();
    } finally {
      loadAbort = null;
    }
  }

  function cancelLoad() {
    loadAbort?.abort();
    state.phase = 'idle';
    renderStage();
  }

  function setVoice(id) {
    state.voice = id;
    try {
      localStorage.setItem(VOICE_KEY, id);
    } catch {
      // Not persisted.
    }
  }

  // ---------- speech ----------
  function playFrame(pcm) {
    if (!audio) return;
    const buf = audio.createBuffer(1, pcm.length, tts.sampleRate);
    buf.copyToChannel(pcm, 0);
    const node = audio.createBufferSource();
    node.buffer = buf;
    node.connect(audio.destination);
    const now = audio.currentTime;
    if (nextAt < now + 0.005) {
      if (nextAt > 0) state.run.underruns++;
      nextAt = now + LEAD_SEC;
    }
    node.start(nextAt);
    nextAt += buf.duration;
  }

  async function speak() {
    const text = input.value.trim();
    if (!text || !tts || state.speak === 'speaking') return;
    stopAudio();
    // Created on the click, so the browser allows playback.
    try {
      audio = new AudioContext({ sampleRate: tts.sampleRate });
    } catch {
      audio = null;
    }
    nextAt = 0;
    speakAbort = new AbortController();
    const voice = voiceSelect.value;
    const chunks = tts.plan(text);
    state.run = { pcm: [], stats: null, chunk: 0, chunks: chunks.length, frames: 0, text, underruns: 0, startedAt: performance.now() };
    Object.assign(state, { speak: 'speaking', error: null });
    wave.clear();
    renderReady();
    renderMetrics();
    try {
      const stats = await tts.speak(text, {
        voice,
        seed: hashString(`${voice}:${text}`),
        signal: speakAbort.signal,
        onAudio: (pcm, info) => {
          if (disposed) return;
          const run = state.run;
          run.pcm.push(pcm);
          run.frames++;
          run.chunk = info.chunk;
          run.firstAudioMs ??= performance.now() - run.startedAt;
          playFrame(pcm);
          scheduleDraw();
          updateStatus();
          if (run.frames === 1 || run.frames % 6 === 0) renderMetrics();
        },
      });
      if (disposed) return;
      state.run.stats = stats;
      state.speak = 'done';
    } catch (err) {
      if (disposed) return;
      if (err.name === 'AbortError') state.speak = 'done';
      else Object.assign(state, { speak: 'error', error: err.message });
    } finally {
      speakAbort = null;
    }
    renderReady();
    renderMetrics();
  }

  function stop() {
    speakAbort?.abort();
    stopAudio();
  }

  function stopAudio() {
    if (audio) audio.close().catch(() => {});
    audio = null;
  }

  function replay() {
    const pcm = state.run && concat(state.run.pcm);
    if (!pcm?.length) return;
    stopAudio();
    audio = new AudioContext({ sampleRate: tts.sampleRate });
    nextAt = 0;
    playFrame(pcm);
    state.run.underruns = 0;
  }

  function download() {
    const pcm = state.run && concat(state.run.pcm);
    if (!pcm?.length) return;
    const url = URL.createObjectURL(new Blob([encodeWav(pcm, tts.sampleRate)], { type: 'audio/wav' }));
    const a = h('a', { href: url, download: 'phonon-speech.wav' });
    document.body.append(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 10000);
  }

  function scheduleDraw() {
    if (raf) return;
    raf = requestAnimationFrame(() => {
      raf = 0;
      const pcm = concat(state.run?.pcm ?? []);
      wave.showClip(pcm);
      clock.textContent = formatClock(pcm.length / (tts?.sampleRate ?? 24000), { tenths: true });
    });
  }

  // ---------- rendering ----------
  function renderAll() {
    renderVoices();
    renderStage();
    renderMetrics();
  }

  function renderVoices() {
    const voices = state.source?.spec?.voices ?? [];
    replace(voiceSelect, voices.map((v) => h('option', { value: v.id }, v.label)));
    if (voices.some((v) => v.id === state.voice)) voiceSelect.value = state.voice;
    voiceSelect.disabled = !voices.length;
  }

  function renderStage() {
    if (disposed) return;
    if (state.phase === 'ready') return renderReady();
    stage.classList.remove('tts-stage--ready');
    replace(stage, h('div', { class: 'tts-stage__center' }, stageBody()));
  }

  function stageBody() {
    const size = formatBytes(model.approxBytes, { approx: model.approxBytesIsEstimate });
    if (state.phase === 'checking') return h('div', { class: 'preload' }, h('div', { class: 'app-glyph', 'aria-hidden': 'true' }, appIcon(demo.id, 64)), h('p', { class: 'preload__sub' }, 'Checking for the model…'));
    if (state.phase === 'unavailable') {
      return h(
        'div',
        { class: 'preload' },
        h('div', { class: 'preload__glyph' }, icon('lock', 26)),
        h('h2', { class: 'preload__title' }, 'Not available in this build'),
        h('p', { class: 'preload__sub' }, `${model.name} (${size}) is not hosted here yet, so nothing can be downloaded or spoken.`),
        licenseBadgeEl(model),
        state.reasons.length ? h('ul', { class: 'tts-reasons' }, state.reasons.map((r) => h('li', null, r.text))) : null,
      );
    }
    const gpu = state.gpu;
    if (gpu.status === 'unavailable' || gpu.status === 'lost') return gpuFallbackPanel(gpu, { compact: true });
    if (state.phase === 'loading') return loaderEl();
    return h(
      'div',
      { class: 'preload' },
      h('div', { class: 'app-glyph', 'aria-hidden': 'true' }, appIcon(demo.id, 64)),
      h('h2', { class: 'preload__title' }, model.name),
      h('p', { class: 'preload__sub' }, `Text to speech · ${size} · runs on your GPU`),
      state.phase === 'error' ? h('div', { class: 'inline-error' }, icon('alert', 16), h('span', null, state.loadError)) : null,
      h(
        'button',
        { class: 'btn btn--primary btn--xl', type: 'button', disabled: gpu.status !== 'ready', onclick: () => load() },
        icon('download', 18),
        state.phase === 'error' ? 'Try again' : `Download & load (${size})`,
      ),
      h(
        'div',
        { class: 'preload__facts' },
        h('p', { class: 'preload__note' }, 'Downloads once, then your browser keeps a copy.'),
        hfBadge(state.source),
        onDeviceNote(model),
        modelCredit(),
        normalizationNote(),
      ),
    );
  }

  function modelCredit() {
    return h('div', { class: 'tts-credit' }, creditEl(model), attributionEl(model), h('p', { class: 'tts-license' }, 'Apache 2.0'));
  }

  function normalizationNote() {
    return h('p', { class: 'preload__note' }, 'Text normalization (numbers, dates, symbols) is basic in this demo.');
  }

  let loaderParts = null;
  function loaderEl() {
    const bar = h('div', { class: 'progress__bar' });
    const detail = h('p', { class: 'loader__detail' });
    const steps = LOAD_STAGES.map((s) => h('li', { class: 'steps__item' }, h('span', { class: 'steps__dot' }), s.label));
    loaderParts = { bar, detail, steps };
    const el = h(
      'div',
      { class: 'loader' },
      h('div', { class: 'app-glyph', 'aria-hidden': 'true' }, appIcon(demo.id, 64)),
      h('h2', { class: 'loader__title' }, `Loading ${model.shortName}`),
      h('div', { class: 'progress', role: 'progressbar', 'aria-label': 'Loading progress' }, bar),
      detail,
      h('ul', { class: 'steps' }, steps),
      hfBadge(state.source),
      h('button', { class: 'btn btn--ghost btn--sm', type: 'button', onclick: () => cancelLoad() }, 'Cancel'),
    );
    updateLoader();
    return el;
  }

  function updateLoader() {
    if (!loaderParts || state.phase !== 'loading') return;
    const { stage: cur, fractions, loaded, total, detail } = state.load;
    const idx = Math.max(0, LOAD_STAGES.findIndex((s) => s.id === cur));
    let overall = 0;
    LOAD_STAGES.forEach((s, i) => (overall += s.weight * (i < idx ? 1 : i === idx ? (fractions[s.id] ?? 0) : 0)));
    LOAD_STAGES.forEach((_, i) => {
      loaderParts.steps[i].className = i < idx ? 'steps__item is-done' : i === idx ? 'steps__item is-active' : 'steps__item';
    });
    loaderParts.bar.style.width = `${(overall * 100).toFixed(1)}%`;
    loaderParts.detail.textContent =
      cur === 'download' && total ? `${formatBytes(loaded)} of ${formatBytes(total)}` : cur === 'gpu' ? `Preparing the ${detail || 'programs'}…` : cur === 'runtime' ? 'Starting WebGPU…' : '';
  }

  function renderReady() {
    if (disposed || state.phase !== 'ready') return;
    stage.classList.add('tts-stage--ready');
    replace(
      stage,
      h('div', { class: 'tts-stage__top' }, h('span', { class: 'tts-ready' }, h('span', { class: 'tts-ready__dot' }), `${model.shortName} ready`), countEl),
      input,
      h('div', { class: 'tts-samples' }, SAMPLES.map((s) => h('button', { class: 'suggest', type: 'button', onclick: () => pick(s) }, s))),
      h('div', { class: 'tts-actions' }, speakBtn, h('p', { class: 'tts-note' }, 'Normalization is basic: numbers, money and a few symbols are spelled; dates, times and links are read as written.')),
      h('div', { class: state.speak === 'speaking' ? 'tts-player tts-player--live' : 'tts-player' }, h('div', { class: 'tts-player__wave' }, waveCanvas, clock), statusEl),
      h('div', { class: 'tts-player__actions' }, replayBtn, downloadBtn),
      state.speak === 'error' ? h('div', { class: 'inline-error' }, icon('alert', 16), h('span', null, state.error)) : null,
    );
    wave.redraw();
    updateControls();
    updateStatus();
  }

  function pick(text) {
    input.value = text;
    updateControls();
    input.focus();
  }

  function updateControls() {
    const speaking = state.speak === 'speaking';
    replace(speakBtn, speaking ? [icon('stop', 16), 'Stop'] : [icon('play', 16), 'Speak']);
    speakBtn.disabled = !speaking && !input.value.trim();
    input.disabled = speaking;
    const has = Boolean(state.run?.pcm.length) && !speaking;
    downloadBtn.disabled = !has;
    replayBtn.disabled = !has;
    countEl.textContent = `${input.value.length} / ${MAX_CHARS}`;
  }

  function updateStatus() {
    const run = state.run;
    if (!run) return replace(statusEl, 'Press Speak. Audio starts playing as soon as the first frame is decoded.');
    const sec = (run.frames * 1920) / (tts?.sampleRate ?? 24000);
    if (state.speak === 'speaking') {
      return replace(statusEl, h('span', { class: 'tts-dot' }), run.chunks > 1 ? `Speaking sentence ${run.chunk + 1} of ${run.chunks}` : 'Speaking', ` · ${formatInt(run.frames)} frames · ${sec.toFixed(1)} s of audio`);
    }
    if (state.speak === 'done' && run.stats) return replace(statusEl, `Done: ${sec.toFixed(1)} s of audio in ${formatMs(run.stats.ms)}.`);
    if (state.speak === 'done') return replace(statusEl, `Stopped after ${sec.toFixed(1)} s of audio.`);
    return replace(statusEl, '');
  }

  function renderMetrics() {
    const run = state.run;
    const s = run?.stats;
    const elapsed = s?.ms ?? (run ? performance.now() - run.startedAt : null);
    const audioSec = run ? (run.frames * 1920) / (tts?.sampleRate ?? 24000) : 0;
    const rtf = run && audioSec > 0 ? elapsed / 1000 / audioSec : null;
    const perFrame = s && s.frames ? (s.flowMs + s.mimiMs) / s.frames : null;
    replace(
      metricsPanel,
      h('h2', { class: 'metrics__title' }, 'This run'),
      h(
        'div',
        { class: 'metric-grid' },
        metricTile('Load', formatMs(state.loadMs), 'download + GPU setup'),
        metricTile('First audio', formatMs(run?.firstAudioMs), 'after you press Speak'),
        metricTile('Real-time factor', rtf == null ? '—' : rtf.toFixed(2), 'generation time ÷ audio length; below 1 is faster than real time'),
        metricTile('Frames', run ? formatInt(run.frames) : '—', run ? `80 ms each · ${formatInt(run.chunks)} sentence${run.chunks === 1 ? '' : 's'}` : '80 ms of audio each'),
      ),
      s
        ? h(
            'p',
            { class: 'metrics__note' },
            `Per frame: ${formatMs(s.flowMs / s.frames)} speech model + ${formatMs(s.mimiMs / s.frames)} audio decoder (${formatMs(perFrame)}; real time needs under 80 ms).`,
            run.underruns ? ` Playback waited for the GPU ${run.underruns} time${run.underruns === 1 ? '' : 's'}.` : '',
          )
        : null,
      h('h3', { class: 'metrics__h' }, 'How it works'),
      h(
        'ul',
        { class: 'opt-list' },
        [
          'Two ExecuTorch .pte programs (fp32), each one WebGPU delegate',
          'A 6-layer flow transformer predicts one audio latent per 80 ms frame; its KV cache stays on the GPU',
          'The Mimi decoder turns each latent into 1,920 samples at 24 kHz, streaming',
          'Text is normalized and tokenized in JavaScript; long text is spoken sentence by sentence',
          'Playback starts with the first decoded frame',
        ].map((t) => h('li', null, icon('check', 14), t)),
      ),
      h('h3', { class: 'metrics__h' }, 'Model'),
      modelCredit(),
    );
  }

  return () => {
    disposed = true;
    loadAbort?.abort();
    speakAbort?.abort();
    stopAudio();
    cancelAnimationFrame(raf);
    wave.dispose();
    unsubscribeGpu();
  };
}
