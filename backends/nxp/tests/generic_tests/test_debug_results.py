class TestNsysDebugResults:
    @staticmethod
    def _assert_artifacts_presence(
        test_dir: pathlib.Path,
        num_examples: int,
        num_inputs: int = 1,
        num_outputs: int = 1,
        ref_dataset: bool = False,
        quant_dataset: bool = False,
    ):
        """Assert that exactly the expected debug artifacts created by `lower_run_compare` are present.

        Fails if any expected artifact is missing or if any unexpected file is present in `test_dir`.

        :param test_dir: Test artifacts directory, as returned by `get_test_dir`.
        :param num_examples: Number of examples generated by the dataset creator passed to `lower_run_compare`.
        :param num_inputs: Number of model inputs. Multi-input examples are stored in per-example subdirectories.
        :param num_outputs: Number of model outputs.
        :param ref_dataset: True if a custom `reference_input_spec` was used, so `ref_dataset` is created.
        :param quant_dataset: True if run with `remove_quant_io_ops`, so quantized datasets are created.
        """

        # Return the given files plus their .txt variants, e.g. [0000.bin] -> [0000.bin, 0000.txt].
        def _with_txt(files: list[str]) -> list[str]:
            return files + [f"{os.path.splitext(f)[0]}.txt" for f in files]

        # Handle artifacts based on number of inputs
        if num_inputs == 1:
            samples_input = [f"{idx:04d}.bin" for idx in range(num_examples)]
            input_files = samples_input
        else:
            samples_input = [f"{idx:04d}" for idx in range(num_examples)]
            input_files = [
                os.path.join(sample, f"{input_idx:04d}.bin")
                for sample in samples_input
                for input_idx in range(num_inputs)
            ]

        output_files = [f"{output_idx:04d}.bin" for output_idx in range(num_outputs)]

        expected_files = [
            "summary.yaml",
            "tag1_neutron.et.tflite",
            "tag1_pure.et.tflite",
        ]
        # model_delegated.pte, model_delegated.json, model_non_quantized.pte, ...
        expected_files += [
            f"{program}.{ext}"
            for program in [
                "model_delegated",
                "model_non_delegated",
                "model_non_quantized",
            ]
            for ext in ["pte", "json"]
        ]
        # results_cpu/results.txt, results_npu/trace.etdump, ...
        # The runner writes results.txt (top-1 class) only for single output models run in
        # `--dataset` mode, which is used for single input models only.
        result_summary_files = ["trace.etdump"]
        if num_inputs == 1 and num_outputs == 1:
            result_summary_files.append("results.txt")
        expected_files += [
            os.path.join(results_dir_name, file)
            for results_dir_name in [RESULTS_CPU_DIR_NAME, RESULTS_NPU_DIR_NAME]
            for file in result_summary_files
        ]
        # results_cpu/0000.bin/0000.bin, results_npu/0000.bin/0000.txt, ...
        expected_files += [
            os.path.join(results_dir_name, sample, file)
            for results_dir_name in [
                RESULTS_CPU_DIR_NAME,
                RESULTS_NPU_DIR_NAME,
                DIFF_CPU_NPU_DIR_NAME,
            ]
            for sample in samples_input
            for file in _with_txt(output_files)
        ]
        # Datasets as (dir, files). The .txt variants are created only for the datasets used to run
        # the models. Quantized runs are tested on the `_quant` datasets instead of the `test` ones.
        test_files = input_files if quant_dataset else _with_txt(input_files)
        datasets = [
            (os.path.join("model_dataset", "calibration"), _with_txt(input_files)),
            (os.path.join("model_dataset", "test"), test_files),
        ]
        if ref_dataset:
            datasets += [
                (os.path.join("ref_dataset", "calibration"), _with_txt(input_files)),
                (os.path.join("ref_dataset", "test"), test_files),
            ]
        if quant_dataset:
            datasets += [
                ("model_dataset_quant", _with_txt(input_files)),
                ("ref_dataset_quant", _with_txt(input_files)),
            ]
        # model_dataset/calibration/0000.bin, model_dataset/calibration/0000.txt, ...
        expected_files += [
            os.path.join(dataset_dir, file)
            for dataset_dir, files in datasets
            for file in files
        ]

        expected_files += ["all_close_stats.csv"]

        expected_files = set(expected_files)
        actual_files = {
            os.path.relpath(os.path.join(root, file), test_dir)
            for root, _, files in os.walk(test_dir)
            for file in files
        }

        missing_files = sorted(expected_files - actual_files)
        extra_files = sorted(actual_files - expected_files)
        assert not missing_files, f"Missing artifacts in '{test_dir}': {missing_files}"
        assert not extra_files, f"Unexpected artifacts in '{test_dir}': {extra_files}"

        assert os.path.isfile(f"{test_dir}.zip")

    @staticmethod
    def _assert_pytest_info(
        pytest_info: PytestInfo,
        file_parent: pathlib.Path,
        file_name: str,
        case_name: str,
        case_id: str | None,
    ):
        """Assert that `pytest_info` describes the currently running test.

        :param pytest_info: Info returned by `get_pytest_info` for the current test.
        :param file_parent: Resolved directory of the test file.
        :param file_name: Test file name.
        :param case_name: Test function name.
        :param case_id: Expected parametrize id, None for non-parametrized tests.
        """
        # Resolve to be independent of symlinks (e.g. src/executorch/backends -> backends).
        assert pathlib.Path(pytest_info.file_parent).resolve() == file_parent
        assert pytest_info.file_name == file_name
        assert pytest_info.case_name == case_name
        assert pytest_info.case_id == case_id

        expected_full_id = "::".join(
            field
            for field in [
                pytest_info.file_parent,
                pytest_info.file_name,
                pytest_info.case_name,
                pytest_info.case_id,
            ]
            if field is not None
        )
        assert str(pytest_info) == expected_full_id

    @staticmethod
    def _assert_debug_summary_content(test_dir: pathlib.Path, pytest_info: PytestInfo):
        """Assert that `summary.yaml` has the expected content and `test_name_mapping.yaml` maps the test dir.

        :param test_dir: Test artifacts directory.
        :param pytest_info: Info of the test which produced the artifacts.
        """
        with open(os.path.join(test_dir, "summary.yaml")) as f:
            summary = yaml.safe_load(f)

        # Exactly the expected keys, nothing missing or extra
        assert set(summary.keys()) == SUMMARY_YAML_KEYS

        # Check information about the test is stored correctly.
        assert summary["test_file_parent"] == pytest_info.file_parent
        assert summary["test_file_name"] == pytest_info.file_name
        assert summary["test_case_name"] == pytest_info.case_name
        assert summary["test_case_id"] == pytest_info.case_id
        assert summary["test_full_id"] == str(pytest_info)

        # Check date is set and in correct format
        date_time = summary["date_time"]
        if isinstance(date_time, str):
            date_time = datetime.datetime.fromisoformat(date_time)
        assert isinstance(date_time, datetime.datetime)

        # Commit is always set, branch might not because of possible DETACHED state.
        assert isinstance(summary["git_branch"], str)
        assert isinstance(summary["git_commit"], str) and summary["git_commit"]
        assert (
            isinstance(summary["eiq_neutron_sdk_version"], str)
            and summary["eiq_nsys_version"]
        )

        # Check correctness of dir name mapping
        mapping_path = os.path.join(OUTPUTS_DIR, "test_name_mapping.yaml")
        assert os.path.isfile(mapping_path)
        with open(mapping_path) as f:
            test_name_mapping = yaml.safe_load(f)

        assert test_name_mapping[test_dir.name] == str(pytest_info)

    @pytest.mark.parametrize(
        "test_case_id, ref_dim_order, remove_quant_io_ops",
        [
            pytest.param(
                "same dim order, quant io ops kept",
                torch.contiguous_format,
                False,
                id="same dim order, quant io ops kept",
            ),
            pytest.param(
                "same dim order, quant io ops removed",
                torch.contiguous_format,
                True,
                id="same dim order, quant io ops removed",
            ),
            pytest.param(
                "channels last ref, quant io ops kept",
                torch.channels_last,
                False,
                id="channels last ref, quant io ops kept",
            ),
            pytest.param(
                "channels last ref, quant io ops removed",
                torch.channels_last,
                True,
                id="channels last ref, quant io ops removed",
            ),
        ],
    )
    def test_debug_results__one_input_output(
        self, caplog, request, test_case_id, ref_dim_order, remove_quant_io_ops
    ):
        # Set log level to DEBUG to create debug results
        caplog.set_level(logging.DEBUG)

        case_name = inspect.currentframe().f_code.co_name
        case_id = test_case_id.replace(" ", "_")

        input_shape = (2, 4, 6, 7)
        model = AvgPool2dModule(False)

        graph_verifier = BaseGraphVerifier(1, [])

        num_examples = 3
        dataset_creator = RandomDatasetCreator(num_examples=num_examples)

        ref_dataset = ref_dim_order != torch.contiguous_format
        reference_input_spec = None
        if ref_dataset:
            reference_input_spec = [
                ModelInputSpec(input_shape, dim_order=ref_dim_order)
            ]

        lower_run_compare(
            model,
            input_shape,
            graph_verifier,
            request,
            dataset_creator=dataset_creator,
            remove_quant_io_ops=remove_quant_io_ops,
            reference_input_spec=reference_input_spec,
        )

        # Assert PyTest info correctness
        pytest_info = get_pytest_info(request)
        self._assert_pytest_info(
            pytest_info, FILE_PARENT, FILE_NAME, case_name, case_id
        )

        # Assert artifacts correctness
        test_dir = get_test_dir(pytest_info)
        self._assert_artifacts_presence(
            test_dir,
            num_examples,
            ref_dataset=ref_dataset,
            quant_dataset=remove_quant_io_ops,
        )

        # Assert debug summary dumps correctness
        self._assert_debug_summary_content(test_dir, pytest_info)

