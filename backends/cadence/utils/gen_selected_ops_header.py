"""Write a C++ header that lists the operator names in a selected_operators.yaml
produced by codegen/tools/gen_oplist.py, as `kSelectedOps`."""

import argparse
import os

import yaml


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--oplist-yaml", required=True)
    parser.add_argument("--output-path", required=True)
    args = parser.parse_args()

    with open(args.oplist_yaml) as f:
        ops = sorted(yaml.safe_load(f)["operators"])
    assert ops, f"{args.oplist_yaml} selects no operators"

    entries = "".join(f'    "{op}",\n' for op in ops)
    with open(args.output_path, "w") as f:
        f.write(
            f"// Generated by {os.path.basename(__file__)} from "
            f"{os.path.basename(args.oplist_yaml)}. Do not edit.\n"
            "#pragma once\n"
            "\n"
            f"constexpr const char* kSelectedOps[] = {{\n{entries}}};\n"
        )


if __name__ == "__main__":
    main()
